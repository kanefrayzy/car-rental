// Brand files, built from the approved logo (a Recraft vector generation; see generations.log).
// No network, no generation: run it again after replacing the source.
//
//   node scripts/brand.mjs
//
// The source is a traced SVG: letter shapes, white shapes on top of them for the holes
// (the counters of B and O), a white background, and slivers of grey anti-aliasing at the tips
// of the cuts. This keeps the navy and blue letters, turns the white counters into real holes
// (fill-rule evenodd), drops the rest, and crops to the letters. Outputs:
//
//   frontend/components/ui/logoPaths.ts  the logo for the site (inline SVG, see Logo.tsx)
//   frontend/public/brand/               logo.svg, logo-white.svg, logo.png,
//                                        icon-192.png, icon-512.png, icon-maskable-512.png
//   frontend/app/                        icon.svg, favicon.ico, apple-icon.png, opengraph-image.jpg
//   backend/resources/views/filament/brand-logo.blade.php, backend/public/favicon.ico,
//   backend/resources/brand/email-logo.png
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "design", "generated", "logo-r3-stencil.svg");
const heroScene = join(root, "design", "generated", "hero-scene-v9.webp");
const frontend = join(root, "frontend");
const brandDir = join(frontend, "public", "brand");

// Site tokens (frontend/app/globals.css): --color-navy, --color-brand-deep, --color-page.
const NAVY = "#0f2035";
const BLUE = "#0566fb";
const PAGE = "#fcfdfe";

const written = [];
async function write(path, data) {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, data);
  written.push(relative(root, path).replaceAll("\\", "/"));
}

// ---------------------------------------------------------------------------
// Parse the source into letters.
// ---------------------------------------------------------------------------

const svg = await readFile(source, "utf8");
const round = (d) => d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n) * 10) / 10));
const shapes = [...svg.matchAll(/<path ([^>]*?)d="([^"]*)"([^>]*)>/g)].map((m) => {
  const fill = /fill="rgb\((\d+),(\d+),(\d+)\)"/.exec(m[1] + m[3]).slice(1).map(Number);
  const numbers = m[2].match(/-?\d+(\.\d+)?/g).map(Number);
  const xs = numbers.filter((_, i) => i % 2 === 0);
  const ys = numbers.filter((_, i) => i % 2 === 1);
  const box = { x0: Math.min(...xs), y0: Math.min(...ys), x1: Math.max(...xs), y1: Math.max(...ys) };
  return { d: round(m[2].trim()), fill: fill.join(","), box };
});

const isNavy = (s) => s.fill === "15,32,53";
const isBlue = (s) => s.fill === "5,102,251";
const isWhite = (s) => s.fill === "255,255,255";
const inside = (a, b) => a.x0 >= b.x0 && a.y0 >= b.y0 && a.x1 <= b.x1 && a.y1 <= b.y1;

const letters = shapes
  .filter((s) => isNavy(s) || isBlue(s))
  .map((letter) => {
    const holes = shapes.filter((s) => isWhite(s) && inside(s.box, letter.box));
    return { d: [letter.d, ...holes.map((h) => h.d)].join(" "), accent: isBlue(letter), box: letter.box };
  })
  .sort((a, b) => Number(a.accent) - Number(b.accent) || a.box.x0 - b.box.x0);

const holesUsed = shapes.filter((s) => isWhite(s) && letters.some((l) => inside(s.box, l.box))).length;
const whites = shapes.filter(isWhite).length - 1; // minus the background
if (holesUsed !== whites) throw new Error(`expected every white shape to be a counter (${holesUsed} of ${whites})`);

/** Exact bounding box of some shapes, measured by rendering them (path control points overshoot). */
async function measure(paths) {
  const markup = `<svg xmlns="http://www.w3.org/2000/svg" width="2048" height="2048" viewBox="0 0 2048 2048">${paths
    .map((p) => `<path fill-rule="evenodd" d="${p.d}"/>`)
    .join("")}</svg>`;
  const { info } = await sharp(Buffer.from(markup)).trim({ threshold: 1 }).toBuffer({ resolveWithObject: true });
  return { x: -info.trimOffsetLeft, y: -info.trimOffsetTop, width: info.width, height: info.height };
}

const pad = 2;
const box = await measure(letters);
const viewBox = [box.x - pad, box.y - pad, box.width + 2 * pad, box.height + 2 * pad];

const logoSvg = (main, accent) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox.join(" ")}">${letters
    .map((l) => `<path fill="${l.accent ? accent : main}" fill-rule="evenodd" d="${l.d}"/>`)
    .join("")}</svg>\n`;

