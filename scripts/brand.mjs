// ---------------------------------------------------------------------------
// The icon: the B of the logo, white on a navy square, with a blue bar like "EXOTICS".
// ---------------------------------------------------------------------------

const b = letters.filter((l) => !l.accent).sort((p, q) => p.box.x0 - q.box.x0)[0];
const bBox = await measure([b]);

/**
 * @param size   pixels
 * @param radius corner radius as a share of the size (0 for full bleed, iOS rounds its own)
 * @param scale  B width as a share of the size (smaller for maskable icons, which get cropped)
 * @param withBar the blue bar under the B (left out at 16px, where it is a one-pixel smudge)
 */
function iconSvg({ size = 512, radius = 0.22, scale = 0.64, withBar = true } = {}) {
  const k = (size * scale) / bBox.width;
  const bar = { width: bBox.width * k, height: withBar ? size * 0.06 : 0 };
  const gap = withBar ? size * 0.05 : 0;
  const total = bBox.height * k + gap + bar.height;
  const top = (size - total) / 2;
  const left = (size - bBox.width * k) / 2;
  // The bar leans like the letters: its bottom edge starts a little to the left.
  const lean = bar.height * 0.6;
  const barTop = top + bBox.height * k + gap;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
<rect width="${size}" height="${size}" rx="${size * radius}" fill="${NAVY}"/>
<g transform="translate(${left} ${top}) scale(${k}) translate(${-bBox.x} ${-bBox.y})"><path fill="#ffffff" fill-rule="evenodd" d="${b.d}"/></g>
${withBar ? `<path fill="${BLUE}" d="M${left + lean} ${barTop}H${left + bar.width}L${left + bar.width - lean} ${barTop + bar.height}H${left}Z"/>` : ""}
</svg>\n`;
}

const png = (markup, size) => sharp(Buffer.from(markup), { density: 300 }).resize(size, size).png().toBuffer();

await write(join(frontend, "app", "icon.svg"), iconSvg());
await write(join(frontend, "app", "apple-icon.png"), await png(iconSvg({ radius: 0, scale: 0.6 }), 180));
await write(join(brandDir, "icon-192.png"), await png(iconSvg(), 192));
await write(join(brandDir, "icon-512.png"), await png(iconSvg(), 512));
await write(join(brandDir, "icon-maskable-512.png"), await png(iconSvg({ radius: 0, scale: 0.5 }), 512));

/** A .ico holding PNG images (supported by every browser that still asks for one). */
async function ico(sizes) {
  const images = await Promise.all(
    sizes.map((size) => png(size <= 16 ? iconSvg({ radius: 0.16, scale: 0.8, withBar: false }) : iconSvg(), size)),
  );
  const header = Buffer.alloc(6 + 16 * sizes.length);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(sizes.length, 4);
  let offset = header.length;
  sizes.forEach((size, i) => {
    const entry = 6 + 16 * i;
    header.writeUInt8(size >= 256 ? 0 : size, entry);
    header.writeUInt8(size >= 256 ? 0 : size, entry + 1);
    header.writeUInt16LE(1, entry + 4);
    header.writeUInt16LE(32, entry + 6);
    header.writeUInt32LE(images[i].length, entry + 8);
    header.writeUInt32LE(offset, entry + 12);
    offset += images[i].length;
  });
  return Buffer.concat([header, ...images]);
}

const favicon = await ico([16, 32, 48]);
await write(join(frontend, "app", "favicon.ico"), favicon);
// The admin panel's own copy: locally the API runs on its own port. In production /favicon.ico
// is served by the website (deploy/Caddyfile), which has the same file.
await write(join(root, "backend", "public", "favicon.ico"), favicon);

// ---------------------------------------------------------------------------
// "BE" monogram for Instagram (client, 2026-10-15: "short abbreviated, like BE"): the B and E
// of the logo itself, the E moved to where the U stands so the spacing matches the logo.
// 1080x1080; Instagram crops to a circle, so the letters stay inside its middle.
// ---------------------------------------------------------------------------

const [lB, lU, lE] = letters.filter((l) => !l.accent).sort((p, q) => p.box.x0 - q.box.x0);
const shiftE = lU.box.x0 - lE.box.x0;
const eBox = await measure([lE]);
const beBox = { x: bBox.x, y: Math.min(bBox.y, eBox.y), width: eBox.x + shiftE + eBox.width - bBox.x, height: Math.max(bBox.y + bBox.height, eBox.y + eBox.height) - Math.min(bBox.y, eBox.y) };

// "B^E" (client: "maybe like b^e"): the E small and raised after the B, like an exponent.
const SUP = 0.46;
const supGap = bBox.width * 0.03;
const supBox = { x: bBox.x, y: bBox.y, width: bBox.width + supGap + eBox.width * SUP, height: bBox.height };
const supE = `translate(${bBox.x + bBox.width + supGap} ${bBox.y}) scale(${SUP}) translate(${-eBox.x} ${-eBox.y})`;

function monogramSvg({ background, b: bFill, e: eFill, withBar = false, superscript = false, size = 1080 }) {
  const box = superscript ? supBox : beBox;
  const k = (size * (superscript ? 0.56 : 0.62)) / box.width;
  const barH = withBar ? size * 0.045 : 0;
  const gap = withBar ? size * 0.04 : 0;
  const top = (size - (box.height * k + gap + barH)) / 2;
  const left = (size - box.width * k) / 2;
  const barTop = top + box.height * k + gap;
  const lean = barH * 0.6;
  // Under "B^E" the bar runs under the B only.
  const width = (superscript ? bBox.width : box.width) * k;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
<rect width="${size}" height="${size}" fill="${background}"/>
<g transform="translate(${left} ${top}) scale(${k}) translate(${-box.x} ${-box.y})">
<path fill="${bFill}" fill-rule="evenodd" d="${lB.d}"/>
<path fill="${eFill}" fill-rule="evenodd" transform="${superscript ? supE : `translate(${shiftE} 0)`}" d="${lE.d}"/>
</g>
${withBar ? `<path fill="${BLUE}" d="M${left + lean} ${barTop}H${left + width}L${left + width - lean} ${barTop + barH}H${left}Z"/>` : ""}
</svg>\n`;
}

for (const [name, options] of [
  ["avatar-be", { background: NAVY, b: "#ffffff", e: BLUE }],
  ["avatar-be-bar", { background: NAVY, b: "#ffffff", e: "#ffffff", withBar: true }],
  ["avatar-be-light", { background: PAGE, b: NAVY, e: BLUE }],
  ["avatar-b-pow-e", { background: NAVY, b: "#ffffff", e: BLUE, superscript: true }],
  ["avatar-b-pow-e-bar", { background: NAVY, b: "#ffffff", e: BLUE, superscript: true, withBar: true }],
  ["avatar-b-pow-e-light", { background: PAGE, b: NAVY, e: BLUE, superscript: true }],
]) {
  const markup = monogramSvg(options);
  await write(join(brandDir, `${name}.svg`), markup);
  await write(join(brandDir, `${name}.png`), await sharp(Buffer.from(markup)).png().toBuffer());
}

