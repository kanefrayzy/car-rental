await write(join(brandDir, "logo.svg"), logoSvg(NAVY, BLUE));
await write(join(brandDir, "logo-white.svg"), logoSvg("#ffffff", BLUE));

const logoPng = (width) => sharp(Buffer.from(logoSvg(NAVY, BLUE)), { density: 300 }).resize({ width }).png();
// For search engines (JSON-LD) and anyone who needs a raster copy.
